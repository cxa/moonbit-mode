#!/bin/sh
# Build the tested upstream parser without changing the user's Emacs setup.
set -eu

repo_dir=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
test_dir=$(mktemp -d "${TMPDIR:-/tmp}/moonbit-mode-test.XXXXXX")
trap 'rm -r "$test_dir"' EXIT HUP INT TERM
emacs_bin=${EMACS:-emacs}
compiler=${CC:-cc}
grammar_revision=5435c307c6cf2ef0d508a99047b06f35a4308444

git init --quiet "$test_dir/grammar"
git -C "$test_dir/grammar" fetch --quiet --depth 1 \
  https://github.com/moonbitlang/tree-sitter-moonbit.git "$grammar_revision"
git -C "$test_dir/grammar" checkout --quiet --detach FETCH_HEAD
mkdir "$test_dir/lib"
"$compiler" -O2 -fPIC -shared -I"$test_dir/grammar/src" \
  "$test_dir/grammar/src/parser.c" "$test_dir/grammar/src/scanner.c" \
  -o "$test_dir/lib/libtree-sitter-moonbit.so"

# Keep generated bytecode out of the checkout.
cp "$repo_dir/moonbit-mode.el" "$test_dir/moonbit-mode.el"
"$emacs_bin" -Q --batch --eval '(setq byte-compile-error-on-warn t)' \
  -f batch-byte-compile "$test_dir/moonbit-mode.el"
"$emacs_bin" -Q --batch -L "$test_dir" -l "$repo_dir/test/moonbit-mode-test.el" \
  --eval '(ert-run-tests-batch-and-exit "^moonbit-test-no-parser-")'
MOONBIT_TEST_GRAMMAR_DIR="$test_dir/lib" \
  "$emacs_bin" -Q --batch -L "$test_dir" -l "$repo_dir/test/moonbit-mode-test.el" \
  -f ert-run-tests-batch-and-exit
